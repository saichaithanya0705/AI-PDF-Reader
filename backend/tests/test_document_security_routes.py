def test_split_document_denies_cross_tenant_and_creates_owned_outputs(secured_app):
    _main, database, docs_dir, client = secured_app
    other_document = create_pdf(database, docs_dir, client_id=OTHER_USER_ID, filename="other.pdf")

    denied = client.post(
        "/api/split-document",
        headers=AUTH_HEADERS,
        json={
            "document_id": other_document.id,
            "splits": [
                {"name": "one", "start_page": 1, "end_page": 1},
                {"name": "two", "start_page": 2, "end_page": 2},
            ],
        },
    )

    assert denied.status_code == 404

    owned_document = create_pdf(database, docs_dir, client_id=USER_ID, filename="owned.pdf")
    created = client.post(
        "/api/split-document",
        headers=AUTH_HEADERS,
        json={
            "document_id": owned_document.id,
            "splits": [
                {"name": "../Quarter One", "start_page": 1, "end_page": 1},
                {"name": "Quarter Two", "start_page": 2, "end_page": 2},
            ],
        },
    )

    assert created.status_code == 200
    body = created.json()
    assert body["success"] is True
    assert len(body["split_documents"]) == 2
    for split in body["split_documents"]:
        split_doc = database.get_document_by_id(split["id"], client_id=USER_ID)
        assert split_doc is not None
        assert split_doc.client_id == USER_ID
        assert "\\" not in split_doc.filename
        assert "/" not in split_doc.filename
        assert Path(split_doc.file_path).resolve().is_relative_to(docs_dir.resolve())


def test_merge_documents_denies_cross_tenant_and_creates_owned_output(secured_app):
    _main, database, docs_dir, client = secured_app
    owned = create_pdf(database, docs_dir, client_id=USER_ID, filename="owned-a.pdf")
    other = create_pdf(database, docs_dir, client_id=OTHER_USER_ID, filename="other-a.pdf")

    denied = client.post(
        "/api/merge-documents",
        headers=AUTH_HEADERS,
        json={"document_ids": [owned.id, other.id], "output_name": "merged"},
    )

    assert denied.status_code == 404

    second_owned = create_pdf(database, docs_dir, client_id=USER_ID, filename="owned-b.pdf")
    merged = client.post(
        "/api/merge-documents",
        headers=AUTH_HEADERS,
        json={"document_ids": [owned.id, second_owned.id], "output_name": "../../Merged Final"},
    )

    assert merged.status_code == 200
    merged_id = merged.json()["merged_document"]["id"]
    merged_doc = database.get_document_by_id(merged_id, client_id=USER_ID)
    assert merged_doc is not None
    assert merged_doc.client_id == USER_ID
    assert merged_doc.original_name == "Merged_Final.pdf"
    assert Path(merged_doc.file_path).resolve().is_relative_to(docs_dir.resolve())


