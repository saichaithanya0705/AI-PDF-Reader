def create_pdf(database, docs_dir, client_id=USER_ID, filename="stored.pdf"):
    file_path = docs_dir / filename
    file_path.write_bytes(b"%PDF-1.4\n% test pdf\n")
    return database.create_document(
        filename=filename,
        original_name=filename,
        file_size=file_path.stat().st_size,
        file_path=str(file_path),
        client_id=client_id,
    )


def test_context_upload_failure_keeps_prior_successful_file(secured_app, monkeypatch):
    main, database, _docs_dir, client = secured_app

    async def noop_process_pdf_collection(*_args, **_kwargs):
        return None

    monkeypatch.setattr(main, "process_pdf_collection", noop_process_pdf_collection)
    valid_pdf = b"%PDF-1.4\n% test pdf\n"

    response = client.post(
        "/upload/context_files",
        headers=AUTH_HEADERS,
        files=[
            ("files", ("valid.pdf", valid_pdf, "application/pdf")),
            ("files", ("invalid.pdf", b"not a pdf", "application/pdf")),
        ],
    )

    assert response.status_code == 202
    body = response.json()
    assert [item["status"] for item in body["files"]] == ["queued", "failed"]

    documents = database.get_all_documents(client_id=USER_ID)
    assert len(documents) == 1
    stored_path = Path(documents[0].file_path)
    assert documents[0].original_name == "valid.pdf"
    assert stored_path.exists()
    assert stored_path.read_bytes() == valid_pdf


