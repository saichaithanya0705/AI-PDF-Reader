class FakePdf:
    def __init__(self, pages: int):
        self.pages = pages

    def __len__(self):
        return self.pages

    def insert_pdf(self, source, from_page=None, to_page=None):
        if from_page is None or to_page is None:
            self.pages += len(source)
        else:
            self.pages += to_page - from_page + 1

    def save(self, path):
        Path(path).write_bytes(b"%PDF-1.4\n% generated by test\n")

    def close(self):
        return None


def fake_fitz_open(*args, **kwargs):
    if kwargs.get("stream") is not None:
        return FakePdf(1)
    if not args and not kwargs:
        return FakePdf(0)
    return FakePdf(4)


