    import backend.app.rag_service as rag_service

    other_document = create_pdf(database, docs_dir, client_id=OTHER_USER_ID, filename="other-rag.pdf")
    database.store_chunk(
        document_id=other_document.id,
        chunk_text="other tenant secret",
        chunk_index=0,
        page_number=1,
    )
    calls = []

    class FakeRAGService:
        def delete_document_from_rag(self, document_id, user_id=None):
            calls.append((document_id, user_id))
            return {"success": True, "document_id": document_id}

