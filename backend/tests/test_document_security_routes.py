def test_audio_and_podcast_require_owned_document(secured_app, monkeypatch):
    main, database, docs_dir, client = secured_app
    other_document = create_pdf(database, docs_dir, client_id=OTHER_USER_ID, filename="other-audio.pdf")
    audio_dir = main.DATA_DIR / "temp_audio"
    audio_dir.mkdir(parents=True)
    other_audio_name = f"podcast_{other_document.id}_1_123.wav"
    (audio_dir / other_audio_name).write_bytes(b"RIFFfake")

    denied_audio = client.get(f"/api/audio/{other_audio_name}", headers=AUTH_HEADERS)
    denied_podcast = client.post(
        "/api/generate-podcast",
        headers=AUTH_HEADERS,
        json={
            "document_id": other_document.id,
            "page": 1,
            "selected_text": "This selected text is long enough for podcast generation.",
        },
    )

    assert denied_audio.status_code == 404
    assert denied_podcast.status_code == 404

    class FakeTTS:
        async def generate_podcast(self, _content, _title):
            return b"RIFFowned"

    monkeypatch.setattr(main, "tts_service", FakeTTS())
    owned_document = create_pdf(database, docs_dir, client_id=USER_ID, filename="owned-audio.pdf")
    created = client.post(
        "/api/generate-podcast",
        headers=AUTH_HEADERS,
        json={
            "document_id": owned_document.id,
            "page": 1,
            "selected_text": "This selected text is long enough for podcast generation.",
        },
    )

    assert created.status_code == 200
    audio_url = created.json()["audioUrl"]
    served = client.get(audio_url, headers=AUTH_HEADERS)
    assert served.status_code == 200
    assert served.content == b"RIFFowned"


def test_rag_delete_route_verifies_owner_before_deleting(secured_app, monkeypatch):
    _main, database, docs_dir, client = secured_app
    import backend.app.rag_service as rag_service

    other_document = create_pdf(database, docs_dir, client_id=OTHER_USER_ID, filename="other-rag.pdf")
    database.store_chunk(
        document_id=other_document.id,
        chunk_text="other tenant secret",
        chunk_index=0,
        page_number=1,
    )
    calls = []

    class FakeRAGService:
        def delete_document_from_rag(self, document_id, user_id=None):
            calls.append((document_id, user_id))
            return {"success": True, "document_id": document_id}

    monkeypatch.setattr(rag_service, "get_rag_service", lambda: FakeRAGService())

    denied = client.delete(f"/api/rag/document/{other_document.id}", headers=AUTH_HEADERS)

    assert denied.status_code == 404
    assert calls == []
    assert database.get_chunk_count(other_document.id) == 1

    owned_document = create_pdf(database, docs_dir, client_id=USER_ID, filename="owned-rag.pdf")
    allowed = client.delete(f"/api/rag/document/{owned_document.id}", headers=AUTH_HEADERS)

    assert allowed.status_code == 200
    assert calls == [(owned_document.id, USER_ID)]
